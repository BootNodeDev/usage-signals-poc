// Regenerates the pinned tracker and its manifest from the Umami image pinned in
// docker-compose.yml, using Umami's own COLLECT_API_ENDPOINT rewrite (scripts/update-tracker.js).
// The tracker is Umami's file, MIT licensed: see public/s/UMAMI-LICENSE.txt.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const POC_ROOT = path.resolve(import.meta.dirname, '..')
const COLLECT_ENDPOINT = '/api/e'

function pinnedUmamiImage() {
  const compose = readFileSync(path.join(POC_ROOT, 'docker-compose.yml'), 'utf8')
  const match = compose.match(
    /image:\s*(ghcr\.io\/umami-software\/umami:([\d.]+)@sha256:[0-9a-f]{64})/,
  )
  if (!match) {
    throw new Error(
      'No digest-pinned Umami image found in docker-compose.yml. Pin it as name:version@sha256:...',
    )
  }
  return { image: match[1], version: match[2] }
}

function extractTracker(image) {
  return execFileSync(
    'docker',
    [
      'run',
      '--rm',
      '-e',
      `COLLECT_API_ENDPOINT=${COLLECT_ENDPOINT}`,
      image,
      'sh',
      '-c',
      'node scripts/update-tracker.js >/dev/null && cat public/script.js',
    ],
    { maxBuffer: 1024 * 1024 },
  )
}

const { image, version } = pinnedUmamiImage()
const tracker = extractTracker(image)
if (tracker.includes('/api/send') || !tracker.includes(COLLECT_ENDPOINT)) {
  throw new Error(
    `Tracker from ${image} does not post to ${COLLECT_ENDPOINT}; check COLLECT_API_ENDPOINT support.`,
  )
}

const contentHash = createHash('sha256').update(tracker).digest('hex').slice(0, 8)
const integrity = `sha384-${createHash('sha384').update(tracker).digest('base64')}`
const publicPath = `/s/${version}-${contentHash}/t.js`

const target = path.join(POC_ROOT, 'public', publicPath)
mkdirSync(path.dirname(target), { recursive: true })
writeFileSync(target, tracker)
writeFileSync(
  path.join(POC_ROOT, 'public', 's', 'manifest.json'),
  `${JSON.stringify({ version, image, license: '/s/UMAMI-LICENSE.txt', endpoint: COLLECT_ENDPOINT, path: publicPath, integrity, bytes: tracker.length }, null, 2)}\n`,
)
// The function imports this instead of reading the manifest, so the bundle always carries it.
writeFileSync(
  path.join(POC_ROOT, 'lib', 'tracker.generated.js'),
  '// Generated by scripts/pin-tracker.mjs from public/s/manifest.json. Do not edit.\n' +
    `export const TRACKER = ${JSON.stringify({ version, path: publicPath, integrity }, null, 2)};\n`,
)
console.log(`Pinned ${publicPath} ${integrity}`)
